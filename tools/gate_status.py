#!/usr/bin/env python3
"""Regenerate the "Implementation status" block of knowledge-base/QC-GATES.md from the gate ids the engine actually emits
(`gate("ID", ...)` calls in engine/cves/qc/*.py and engine/cves/assets.py). Run after adding a gate:  python tools/gate_status.py
--check exits 1 if the file is out of date (CI)."""
import os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DOC = os.path.join(ROOT, "knowledge-base", "QC-GATES.md")
QC = os.path.join(ROOT, "engine", "cves", "qc")
RX = re.compile(r"""gate\(\s*["']([A-Z]+-\d+[a-z]?)["']""")

def ids_in(path, start=None, stop=None):
    with open(path, encoding="utf-8") as f: s = f.read()
    if start: s = s[s.index(start):]
    if stop and stop in s: s = s[:s.index(stop)]
    return set(RX.findall(s))

def tuple_ids(path):
    """gates emitted through id lists, e.g. safe(fn, ["PLAT-04", ...]) or for g in ("SND-05", ...)"""
    with open(path, encoding="utf-8") as f: s = f.read()
    return set(re.findall(r"""["']((?:MOT|GFX|PLAT|COL|FRAME|SND|CUT|RET|STORY|DEL|AST)-\d+[a-z]?)["']""", s))

def collect():
    init = os.path.join(QC, "__init__.py")
    final = ids_in(init, None, "def run_stage")
    for f in sorted(os.listdir(QC)):
        if f.endswith(".py") and f not in ("__init__.py",): final |= ids_in(os.path.join(QC, f)) | tuple_ids(os.path.join(QC, f))
    a = os.path.join(ROOT, "engine", "cves", "assets.py")
    if os.path.exists(a): final |= ids_in(a)
    stage = ids_in(init, "def run_stage")
    key = lambda g: (re.sub(r"\d.*", "", g), int(re.search(r"\d+", g).group()), g)
    return sorted(final, key=key), sorted(stage, key=key)

def block(final, stage):
    return "\n".join([
        "## Implementation status (generated by `tools/gate_status.py` from `engine/cves/qc/`)",
        "This table supersedes the per-row \"Implementation\" column below, which predates the engine.",
        f"- **`cves qc` (on the delivered file, {len(final)} gates):** {', '.join(final)}.",
        f"- **`cves qc --stage story|plan` (before rendering, {len(stage)} gates):** {', '.join(stage)}.",
        "- **Enforced by engine defaults, not measured separately:** CUT-04 segment snap; MOT-03 face-smoothed punch-ins and chest graphics; "
        "FRAME-10 no roll/flip; DEL-05 single encode settings (all also measured where listed above).",
        "- **Not automated yet:** every other row below. They are checked by eye (moodboard, contact sheets) or need instruments "
        "not built yet (role/intent tags in the element log, blur and banding detectors, music-stem gates).",
        ""])

def main():
    final, stage = collect()
    with open(DOC, encoding="utf-8") as f: s = f.read()
    a = s.index("## Implementation status"); b = s.index("**Implementation**:", a)
    new = s[:a] + block(final, stage) + "\n" + s[b:]
    new = re.sub(r"`cves qc` measures \d+ of them automatically", f"`cves qc` measures {len(final)} of them automatically", new)
    if "--check" in sys.argv:
        if new != s: print("knowledge-base/QC-GATES.md is out of date: run python tools/gate_status.py"); return 1
        print(f"gate table current: {len(final)} + {len(stage)} stage gates"); return 0
    with open(DOC, "w", encoding="utf-8") as f: f.write(new)
    print(f"{len(final)} gates on the delivered file, {len(stage)} stage gates"); return 0

if __name__ == "__main__":
    sys.exit(main())
